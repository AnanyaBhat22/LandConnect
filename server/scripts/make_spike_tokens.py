"""Generate LiveKit tokens for the day-0 calling spike.

Run from server/:  .venv\\Scripts\\python -m scripts.make_spike_tokens

- Writes app/src/dev/spikeConfig.ts (git-ignored) with the phone's token.
- Prints a browser link so the laptop can join the same room via LiveKit Meet.

Tokens only allow joining room "spike" and expire after 24 hours. The API
secret never leaves the server; only signed, limited tokens are handed out.
This is the same principle the real /calls endpoint will follow.
"""
from datetime import timedelta
from pathlib import Path
from urllib.parse import urlencode

from livekit import api

from app.core.config import settings

ROOM = "spike"
CONFIG_PATH = Path(__file__).resolve().parents[2] / "app" / "src" / "dev" / "spikeConfig.ts"


def make_token(identity: str, name: str) -> str:
    return (
        api.AccessToken(settings.livekit_api_key, settings.livekit_api_secret)
        .with_identity(identity)
        .with_name(name)
        .with_ttl(timedelta(hours=24))
        .with_grants(api.VideoGrants(room_join=True, room=ROOM))
        .to_jwt()
    )


if __name__ == "__main__":
    phone_token = make_token("phone", "Phone")
    laptop_token = make_token("laptop", "Laptop")

    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(
        "// Generated by server/scripts/make_spike_tokens.py. Do not commit.\n"
        f"export const SPIKE_LIVEKIT_URL = '{settings.livekit_url}';\n"
        f"export const SPIKE_TOKEN = '{phone_token}';\n",
        encoding="utf-8",
    )
    print(f"Wrote phone token to {CONFIG_PATH}")
    link = "https://meet.livekit.io/custom?" + urlencode(
        {"liveKitUrl": settings.livekit_url, "token": laptop_token}
    )
    print("\nOpen this on the laptop to join the same room:\n" + link)
